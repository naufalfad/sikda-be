        email: item.email,
        kontakDarurat: item.kontakDarurat,
        kepalaPuskesmas: item.kepalaPuskesmas,
        penanggungJawab: item.penanggungJawab,
        sipPenanggungJawab: item.sipPenanggungJawab,
        nipKepala: item.nipKepala,
        nomorIzinOperasional: item.nomorIzinOperasional,
        akreditasi: item.akreditasi,
        jamOperasional: item.jamOperasional,
        layananUnggulan: item.layananUnggulan,
        fotoUrl: item.fotoUrl,
